// Robo Voice: a robot repeats whatever you play in its one-note voice. MIT.
//
//   SELECTOR   turn: the robot's NOTE (on its chest)        click: TALK (vowels) on/off
//   CUSTOMIZE  turn: METAL (paint .. steel .. chrome)       click: CRUSH off / lo-fi / toy
//              long press: reset
//
// The sound is the nested dsp/ pack (Robo Voice Engine); this file is the robot. The App
// cannot read the pack's state, so the robot acts on the input meter: its mouth and antenna
// follow your playing, a hard pick startles it, and nine quiet seconds put it in low-power
// mode. The artwork is baked pixel art (art.h, generated by ../_art/robo_art.py).
//
// The Web, Mobile and MIDI controllers (controller/, CCs on channel 1, see README.md) reach every
// setting the knobs reach, plus TALK's amount, HARMONY, BREATH, HUM, MIX and LEVEL, and four hold
// pads: SHOUT (chrome, crushed, every vowel), HISS (all breath, no metal), CHORD (the power
// chord) and HIGH (an octave up).
#include <resona/platform.h>
#include <resona/startup_helpers.h>
#include "splash_data.h"
#include "kit.h"
#include "art.h"
#include "controller_link.h"

namespace {

const resona_platform *P;
const char kPack[] = "org.resona.creative.robo-voice.voice";   // dsp/resona.project.json
enum { NOTE, TALK, METAL, CRUSH, MIX, LEVEL, BREATH, HARMONY, HUM, PARAMS };
const float kCrush[3] = {0.0f, 45.0f, 82.0f};
const char *const kNoteName[12] = {"C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"};
const int kColours = (int)(sizeof kArtPalette / sizeof kArtPalette[0]);
enum { GREEN, AMBER, RED, GREEN_LOW, GREEN_MID, CYAN, INK, CREAM };   // the swatch sprite's colours

struct SavedV1 { uint32_t magic; int note, talk, metal, crush; };
struct Saved { uint32_t magic; int note, talk, metal, crush, talk_amt, harmony, breath, hum, mix, level; };
const uint32_t kMagicV1 = 0x524F4231u;   // "ROB1"
const uint32_t kMagic = 0x524F4232u;     // "ROB2"

// The controllers' MIDI map: CC on channel 1 (controller/shared/profile.js says the same).
enum { CC_NOTE = 20, CC_TALK, CC_TALK_AMT, CC_HARMONY, CC_BREATH, CC_METAL, CC_CRUSH, CC_HUM, CC_MIX, CC_LEVEL,
       CC_SHOUT = 30, CC_HISS, CC_CHORD, CC_HIGH };
enum { kBinds = 14 };

struct State {
    kit::Audio audio;
    kit::Levels lv;
    kit::Saver saver;
    Saved s;
    uint32_t ms, idle, blink_at, seed, touched_at, nod_at, zap_at, said_at;
    int touched, vowel;      // touched: 2 = METAL (its value shows on the chest for a moment)
    float pulse;             // a knob touch makes it speak, as a pick does
    float spin, sleep;       // gear/fan angle; 0 awake .. 1 low power
    uint16_t pal[256], dim[256];
    int shout, hiss, chord, high;   // pads held on a controller
    ctl::Link link;
};

ctl::Bind kBind[kBinds];
void bind(State *st)
{
    Saved &s = st->s;
    const ctl::Bind b[kBinds] = {
        {CC_NOTE, ctl::RANGE, 0, 24, &s.note}, {CC_TALK, ctl::STEPS, 0, 1, &s.talk},
        {CC_TALK_AMT, ctl::RANGE, 0, 100, &s.talk_amt}, {CC_HARMONY, ctl::STEPS, 0, 2, &s.harmony},
        {CC_BREATH, ctl::RANGE, 0, 100, &s.breath}, {CC_METAL, ctl::RANGE, 0, 100, &s.metal},
        {CC_CRUSH, ctl::STEPS, 0, 2, &s.crush}, {CC_HUM, ctl::RANGE, 0, 100, &s.hum},
        {CC_MIX, ctl::RANGE, 0, 100, &s.mix}, {CC_LEVEL, ctl::RANGE, -12, 6, &s.level},
        {CC_SHOUT, ctl::TRIGGER, 0, 1, nullptr}, {CC_HISS, ctl::TRIGGER, 0, 1, nullptr},
        {CC_CHORD, ctl::TRIGGER, 0, 1, nullptr}, {CC_HIGH, ctl::TRIGGER, 0, 1, nullptr},
    };
    for (int i = 0; i < kBinds; ++i) kBind[i] = b[i];
}

// The pads override the settings while held: SHOUT wins over HISS.
int note_now(const State *st) { return st->high ? kit::clampi(st->s.note + 12, 0, 24) : st->s.note; }
int metal_now(const State *st) { return st->shout ? 100 : (st->hiss ? 0 : st->s.metal); }
int crush_now(const State *st) { return st->shout ? 2 : (st->hiss ? 0 : st->s.crush); }
int talk_now(const State *st) { return st->shout || st->hiss || st->s.talk; }

uint32_t rnd(State *st) { st->seed = st->seed * 1664525u + 1013904223u; return st->seed >> 8; }
uint32_t hash(uint32_t a) { a ^= a >> 15; a *= 0x2C1B3C6Du; a ^= a >> 12; a *= 0x297A2D39u; return a ^ (a >> 15); }

void push(State *st)
{
    const Saved &s = st->s;
    kit::audio_set(P, st->audio, NOTE, (float)note_now(st));
    kit::audio_set(P, st->audio, TALK, st->shout || st->hiss ? 100.0f : (s.talk ? (float)s.talk_amt : 0.0f));
    kit::audio_set(P, st->audio, METAL, (float)metal_now(st));
    kit::audio_set(P, st->audio, CRUSH, kCrush[crush_now(st)]);
    kit::audio_set(P, st->audio, MIX, (float)s.mix);
    kit::audio_set(P, st->audio, LEVEL, (float)s.level);
    kit::audio_set(P, st->audio, BREATH, st->hiss ? 100.0f : (float)s.breath);
    kit::audio_set(P, st->audio, HARMONY, st->chord ? 2.0f : (float)s.harmony);
    kit::audio_set(P, st->audio, HUM, (float)s.hum);
}

void defaults(State *st) { st->s = {kMagic, 9, 1, 25, 0, 85, 1, 30, 60, 88, 0}; }

void say(State *st)   // a new syllable
{
    st->vowel = (st->vowel + 1 + (int)(rnd(st) % 4u)) % 5;
    st->said_at = st->ms;
}

/* ---- the robot -------------------------------------------------------------------------- */

const kit::Sprite *const kHeads[3] = {&kArt_head_paint, &kArt_head_steel, &kArt_head_chrome};
const kit::Sprite *const kBodies[3] = {&kArt_body_paint, &kArt_body_steel, &kArt_body_chrome};
enum { E_OPEN, E_WIDE, E_HAPPY, E_HALF, E_SHUT, E_SLEEP };
const kit::Sprite *const kEyes[3][6] = {
    {&kArt_eye_open_0, &kArt_eye_wide_0, &kArt_eye_happy_0, &kArt_eye_half_0, &kArt_eye_shut_0, &kArt_eye_sleep_0},
    {&kArt_eye_open_1, &kArt_eye_wide_1, &kArt_eye_happy_1, &kArt_eye_half_1, &kArt_eye_shut_1, &kArt_eye_sleep_1},
    {&kArt_eye_open_2, &kArt_eye_wide_2, &kArt_eye_happy_2, &kArt_eye_half_2, &kArt_eye_shut_2, &kArt_eye_sleep_2},
};
const kit::Sprite *const kBulbs[4] = {&kArt_bulb_0, &kArt_bulb_1, &kArt_bulb_2, &kArt_bulb_3};
const kit::Sprite *const kGearBig[4] = {&kArt_gear_big_0, &kArt_gear_big_1, &kArt_gear_big_2, &kArt_gear_big_3};
const kit::Sprite *const kGearSmall[4] = {&kArt_gear_small_0, &kArt_gear_small_1, &kArt_gear_small_2, &kArt_gear_small_3};
const kit::Sprite *const kFans[4] = {&kArt_fan_0, &kArt_fan_1, &kArt_fan_2, &kArt_fan_3};

void draw(State *st)
{
    kit::Canvas c;
    if (!c.begin(P)) return;
    const uint16_t *lit = kArtPalette;          // things that glow keep their colour in the dark
    for (int i = 0; i < kColours; ++i) st->pal[i] = kit::mix(kArtPalette[i], st->dim[i], st->sleep);
    const uint16_t *pal = st->pal;
    const uint8_t *sw = kArt_swatch_px;
    const bool asleep = st->sleep > 0.5f;
    const float energy = kit::clampf(st->lv.in > st->pulse ? st->lv.in : st->pulse, 0.0f, 1.0f);
    const uint32_t since_zap = st->ms - st->zap_at, since_nod = st->ms - st->nod_at;
    const bool startled = since_zap < 650u;

    c.backdrop(kArt_room, pal);

    // the workshop is alive: gears and the fan turn with the playing, the rack blinks and
    // traces what it hears
    const int turn = (int)st->spin;
    c.blit(*kGearBig[turn & 3], pal, 32, 121);
    c.blit(*kGearSmall[turn & 3], pal, 54, 109);
    c.blit(*kFans[(turn * 2 + (int)(st->spin * 2.0f)) & 3], pal, 277, 117);
    for (int k = 0; k < 5; ++k) {
        static const uint8_t kLamp[5] = {GREEN, AMBER, RED, GREEN, AMBER};
        const bool on = asleep ? (k == 2 && ((st->ms / 700u) & 1u)) : ((hash(st->ms / (260u + (uint32_t)k * 90u) + (uint32_t)k * 77u) & 3u) != 0u && (k < 1 + (int)(energy * 5.0f) || k == 0));
        if (on) c.rect(249 + k * 8, 90, 3, 3, lit[sw[kLamp[k]]]);
    }
    {
        const float amp = asleep ? 0.0f : 1.5f + 8.5f * energy;
        const float t = (float)(st->ms % 6283u) * 0.012f;
        int py = 68;
        for (int x = 0; x < 52; ++x) {
            const int y = 68 + (int)(amp * resona_sinf((float)x * 0.5f + t * 3.0f) * resona_sinf((float)x * 0.13f + 1.0f + t));
            const int a = y < py ? y : py, b = y < py ? py : y;
            c.rect(251 + x, x ? a : y, 1, x ? b - a + 1 : 1, lit[sw[asleep ? GREEN_MID : GREEN]]);
            py = y;
        }
    }

    // the robot: its head nods at a new note, bobs as it talks, jumps when startled, sinks asleep
    int dy = 0;
    if (asleep) dy = 2 + (int)((st->ms / 1500u) & 1u);
    else if (startled && since_zap < 160u) dy = -3;
    else if (since_nod < 110u) dy = 3;
    else if (since_nod < 220u) dy = 1;
    else if (energy > 0.22f) dy = ((st->ms / 130u) & 1u) ? -1 : 0;
    const int metal = metal_now(st), skin = metal < 34 ? 0 : (metal < 67 ? 1 : 2);
    const int ox = kRoboX, oy = kRoboY, hy = oy + dy;
    c.blit(*kBodies[skin], pal, ox, oy);
    c.blit(*kHeads[skin], pal, ox, hy);

    // eyes: little screens (CRUSH makes their pixels big)
    const uint32_t since_blink = st->ms - st->blink_at;
    int eye = E_OPEN;
    if (asleep) eye = E_SLEEP;
    else if (startled) eye = E_WIDE;
    else if (since_blink < 70u || (since_blink >= 140u && since_blink < 200u)) eye = E_HALF;
    else if (since_blink < 140u) eye = E_SHUT;
    else if (energy > 0.3f) eye = E_HAPPY;
    const kit::Sprite &es = *kEyes[crush_now(st)][eye];
    c.blit(es, lit, ox + kEyeL, hy + kEyeY);
    c.blit(es, lit, ox + kEyeR, hy + kEyeY);

    // mouth: an LED matrix. Talking: bars that jump like syllables. Not talking: one humming line.
    if (!asleep || ((st->ms / 900u) & 1u)) {
        for (int k = 0; k < 10; ++k) {
            int h = 1;
            if (asleep) { if (k != 4 && k != 5) continue; }
            else if (talk_now(st)) {
                const float n = (float)(hash(st->ms / 75u * 31u + (uint32_t)k * 7919u) & 255u) * (1.0f / 255.0f);
                const float arch = 1.0f - 0.12f * (float)((k < 5 ? 4 - k : k - 5));
                h = kit::clampi((int)(0.6f + energy * 6.5f * (0.35f + 0.65f * n) * arch), 1, 5);
            } else {
                h = energy > 0.55f ? 2 : 1;
            }
            const uint16_t col = lit[sw[asleep ? GREEN_LOW : (h >= 4 ? AMBER : GREEN)]];
            c.rect(ox + kMouthX + k * 5 + 1, hy + kMouthY + 5 - h, 4, 2 * h, col);
        }
    }

    // antenna: the bulb glows with the playing; a fright makes sparks
    c.blit(*kBulbs[asleep ? 0 : kit::clampi((int)(energy * 3.6f), 0, 3)], asleep ? pal : lit, ox + kBulbX, hy + kBulbY);
    if (startled) {
        const int bx = ox + kBulbX, by = hy + kBulbY, f = (int)(since_zap / 26u);
        if (((since_zap / 80u) & 1u) == 0u) { c.blit(kArt_zap_0, lit, bx - 18, by - 8); c.blit(kArt_zap_1, lit, bx + 12, by - 6); }
        else { c.blit(kArt_zap_1, lit, bx - 20, by - 2, true); c.blit(kArt_zap_0, lit, bx + 14, by - 10, true); }
        c.blit(kArt_spark_big, lit, bx - 10 - f, by + f * f / 12 - 4);
        c.blit(kArt_spark_small, lit, bx + 9 + f, by + f * f / 10 - 6);
        c.blit(kArt_spark_small, lit, bx - 4 - f / 2, by - 9 - f / 3 + f * f / 20);
        c.blit(kArt_spark_big, lit, bx + 16 + f * 3 / 4, by + 2 + f * f / 16);
    }
    if (skin == 2 && !asleep) {   // chrome twinkles
        static const int8_t kAt[4][2] = {{44, 36}, {120, 118}, {112, 46}, {30, 114}};
        const uint32_t k = (st->ms / 420u) & 3u;
        if ((st->ms % 420u) < 240u) c.blit(kArt_twinkle, lit, ox + kAt[k][0], (k == 0 || k == 2 ? hy : oy) + kAt[k][1]);
    }

    // chest display: its note; METAL's amount while that knob turns; a flat battery in low power
    {
        const int gx = ox + kChestX, gy = oy + kChestY;
        const uint16_t green = lit[sw[GREEN]];
        char buf[12];
        if (asleep) {
            if ((st->ms / 450u) % 3u) c.blit(kArt_battery, lit, gx + (kChestW - 26) / 2 + 1, gy + 3);
        } else if (st->touched == 2 && st->ms - st->touched_at < 1100u) {
            P->format(buf, sizeof buf, "%d", st->s.metal);
            c.text(gx + (kChestW - c.text_w(2, buf)) / 2 + 1, gy + 2, 2, lit[sw[AMBER]], buf);
        } else {
            const int note = note_now(st);
            const char *name = kNoteName[note % 12];
            P->format(buf, sizeof buf, "%d", 2 + note / 12);
            const int w = c.text_w(2, name) + 6;
            const int x = gx + (kChestW - w) / 2 + 1;
            c.text(x, gy + 2, 2, green, name);
            c.text(x + w - 5, gy + 9, 1, lit[sw[GREEN_MID]], buf);
        }
    }

    // what it says, or dreams
    if (asleep) {
        for (int k = 0; k < 2; ++k) {
            const int rise = (int)((st->ms / 100u + (uint32_t)k * 12u) % 24u);
            c.blit(k ? kArt_zed_big : kArt_zed_small, lit, ox + 136 + k * 9 + rise / 3, oy + 46 - k * 10 - rise);
        }
    } else if (talk_now(st) && st->ms - st->said_at < 480u) {
        static const char *const kVowel[5] = {"A", "E", "I", "O", "U"};
        const int pop = st->ms - st->said_at < 70u ? 2 : 0;
        c.blit(kArt_bubble, lit, ox + 136, oy + 22 + pop);
        c.text(ox + 136 + 8, oy + 22 + 3 + pop, 2, lit[sw[INK]], kVowel[st->vowel]);
    }

    c.banner(kit::audio_message(st->audio, "INSTALL ROBO VOICE ENGINE IN LAB"), kit::rgb(22, 14, 34), kit::rgb(130, 232, 130));
    c.present(P);
}

/* ---- the App ---------------------------------------------------------------------------- */

int init(void *state, const resona_platform *platform)
{
    State *st = static_cast<State *>(state);
    P = platform;
    const int startup = resona_startup_splash_apply(P, kSplash, sizeof kSplash);
    if (startup < 0 && startup != RESONA_ERR_UNSUPPORTED)
        P->log("Startup animation could not be saved");
    defaults(st);
    Saved v;
    SavedV1 v1;
    if (kit::load(P, v, kMagic)) st->s = v;
    else if (kit::load(P, v1, kMagicV1)) { st->s.note = v1.note; st->s.talk = v1.talk; st->s.metal = v1.metal; st->s.crush = v1.crush; }
    Saved &s = st->s;
    s.note = kit::clampi(s.note, 0, 24); s.talk = s.talk ? 1 : 0; s.metal = kit::clampi(s.metal, 0, 100); s.crush = kit::clampi(s.crush, 0, 2);
    s.talk_amt = kit::clampi(s.talk_amt, 0, 100); s.harmony = kit::clampi(s.harmony, 0, 2); s.breath = kit::clampi(s.breath, 0, 100);
    s.hum = kit::clampi(s.hum, 0, 100); s.mix = kit::clampi(s.mix, 0, 100); s.level = kit::clampi(s.level, -12, 6);
    bind(st);
    st->seed = 0xB07B07u;
    st->zap_at = st->nod_at = st->said_at = st->touched_at = 0u - 100000u;   // long ago
    st->blink_at = 0u - 1000u;
    for (int i = 0; i < kColours; ++i) {   // low-power mode: the same scene, dark and blue
        const uint16_t p = kArtPalette[i];
        const int r = ((p >> 11) & 31) << 3, g = ((p >> 5) & 63) << 2, b = (p & 31) << 3;
        st->dim[i] = kit::rgb(r * 40 / 100, g * 46 / 100, b * 66 / 100);
    }
    push(st);
    return 0;
}

void event(void *state, const resona_app_event *ev)
{
    State *st = static_cast<State *>(state);
    if (kit::audio_event(P, st->audio, ev, st->ms)) return;
    ctl::Msg m;
    if (ctl::receive(P, st->link, kBind, kBinds, ev, m)) {
        if (!m.changed) return;
        if (m.cc == CC_SHOUT) { st->shout = m.down; if (m.down) st->zap_at = st->ms; }
        else if (m.cc == CC_HISS) st->hiss = m.down;
        else if (m.cc == CC_CHORD) st->chord = m.down;
        else if (m.cc == CC_HIGH) { st->high = m.down; st->nod_at = st->ms; }
        else kit::save_later(st->saver, st->ms);
        if (m.cc == CC_NOTE) st->nod_at = st->ms;
        if (m.cc == CC_CRUSH) st->zap_at = st->ms;   // a jolt to its eyes
        st->touched = m.cc == CC_METAL ? 2 : 0;
        st->touched_at = st->ms;
        st->idle = 0;
        if (m.cc < CC_SHOUT || m.down) { st->pulse = 1.0f; say(st); }
        push(st);
        return;
    }
    if (ev->kind != RESONA_APP_EV_INPUT) return;
    const int top = ev->u.input.input == RESONA_INPUT_SELECTOR;
    const int kind = (int)ev->u.input.kind, v = ev->u.input.value;
    if (kind == RESONA_EVENT_TURN) {
        if (top) { st->s.note = kit::clampi(st->s.note + v, 0, 24); st->nod_at = st->ms; }
        else st->s.metal = kit::clampi(st->s.metal + v * 2, 0, 100);
        st->touched = top ? 1 : 2;
        st->touched_at = st->ms;
    } else if (kind == RESONA_EVENT_CLICK) {
        if (top) st->s.talk ^= 1;
        else { st->s.crush = (st->s.crush + 1) % 3; st->zap_at = st->ms; }   // a jolt to its eyes
        st->touched = 0;
    } else if (kind == RESONA_EVENT_LONG && !top) {
        defaults(st);
        st->zap_at = st->ms;
        st->touched = 0;
    } else {
        return;
    }
    st->idle = 0;
    st->pulse = 1.0f;   // it answers every touch
    say(st);
    push(st);
    kit::save_later(st->saver, st->ms);
}

void frame(void *state, uint32_t ms)
{
    State *st = static_cast<State *>(state);
    st->ms += ms;
    kit::audio_tick(P, st->audio, kPack, PARAMS, st->ms);
    kit::levels_tick(P, st->lv, ms);
    kit::save_tick(P, st->saver, st->s, st->ms);
    ctl::sync(P, st->link, kBind, kBinds, st->ms);
    if (st->lv.raw_in >= 2) st->idle = 0; else st->idle += ms;
    if (st->lv.hit > 0.95f) {
        if (st->ms - st->said_at > 120u) say(st);
        if (st->lv.raw_in >= 8 && st->ms - st->zap_at > 1500u) st->zap_at = st->ms;   // a really hard pick
    }
    st->pulse *= resona_expf(-(float)ms / 320.0f);
    const float target = st->idle > 9000u ? 1.0f : 0.0f;
    st->sleep += kit::clampf(target - st->sleep, -(float)ms / 250.0f, (float)ms / 1400.0f);
    const float energy = st->lv.in > st->pulse ? st->lv.in : st->pulse;
    st->spin += (float)ms * (0.0016f + 0.012f * energy) * (1.0f - st->sleep);
    if (st->spin > 4096.0f) st->spin -= 4096.0f;
    if (st->ms - st->blink_at > 2600u + (rnd(st) % 3000u)) st->blink_at = st->ms;
    draw(st);
}

const resona_app kApp = {
    RESONA_PLATFORM_VERSION, sizeof(resona_app),
    RESONA_APP_ID, RESONA_APP_NAME, RESONA_APP_VERSION,
    sizeof(State), 0,
    init, event, frame,
};

}  // namespace

extern "C" const resona_app *resona_app_get(void) { return &kApp; }
