"""Prepare the approved art for live overlays and encode the Box startup pulse."""
from itertools import groupby
from pathlib import Path
import struct
import zlib

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
W, H = 320, 172
scene = Image.open(ROOT / "assets/workshop.png").convert("RGB").resize((W, H), Image.Resampling.LANCZOS)

# Replace the sample speech bubble with nearby pegboard.
mask = Image.new("L", (29, 31))
ImageDraw.Draw(mask).rounded_rectangle((2, 2, 26, 28), radius=4, fill=255)
scene.paste(scene.crop((212, 0, 241, 31)), (211, 25), mask.filter(ImageFilter.GaussianBlur(1)))
draw = ImageDraw.Draw(scene)
# These three displays receive live content from the renderer.
draw.rounded_rectangle((132, 88, 184, 101), radius=3, fill=(3, 18, 15))
draw.rounded_rectangle((137, 128, 181, 149), radius=4, fill=(3, 22, 17))
draw.rounded_rectangle((247, 60, 301, 86), radius=3, fill=(3, 22, 15))
# Keep the glass and rims. Dim only the bright cyan marks already painted in.
for cx in (137, 180):
    for y in range(61, 72):
        for x in range(cx - 9, cx + 10):
            r, g, b = scene.getpixel((x, y))
            if g > 68 and b > 72:
                scene.putpixel((x, y), (min(r, 10), min(g, 50), min(b, 57)))

def rgb565(rgb):
    r, g, b = rgb
    return (r >> 3) << 11 | (g >> 2) << 5 | (b >> 3)

def header(path, name, values, kind):
    rows = [", ".join(map(str, values[i:i + 20])) for i in range(0, len(values), 20)]
    path.write_text("// Generated by tools/encode_workshop.py.\n#pragma once\n#include <stdint.h>\n"
                    f"alignas(4) static const {kind} {name}[] = {{\n"
                    + ",\n".join(rows) + "\n};\n")

header(ROOT / "src/workshop.h", "kWorkshop", [rgb565(p) for p in scene.getdata()], "uint16_t")

# Start on black, then power up the antenna, glass eyes and mouth at their live coordinates.
# Using only light windows keeps the early boot animation within the 24 KiB RSP1 budget.
frames = []
for i in range(15):
    frame = Image.new("RGB", (W, H))
    lights = ImageDraw.Draw(frame)
    antenna = min(1, i / 4)
    eyes = max(0, min(1, (i - 3) / 5))
    mouth = max(0, min(10, i - 5))
    lights.ellipse((154, 11, 162, 19), fill=(int(255 * antenna), int(149 * antenna), int(33 * antenna)))
    for x in (137, 180):
        lights.arc((x - 7, 63, x + 7, 76), 200, 340, fill=(0, int(217 * eyes), int(229 * eyes)), width=2)
    for k in range(mouth):
        h = 2 + (k % 3)
        lights.rectangle((134 + k * 5, 95 - h, 136 + k * 5, 95 + h), fill=(82, 225, 53))
    frames.append(frame)

hold = 38
payload = bytearray()
for frame in frames:
    runs = [(sum(1 for _ in run), color) for color, run in groupby(map(rgb565, frame.getdata()))]
    payload.extend(struct.pack("<II", hold, len(runs)))
    for length, color in runs:
        payload.extend(struct.pack("<HH", length, color))
splash = struct.pack("<4s7I", b"RSP1", len(payload) + 32, zlib.crc32(payload),
                     len(frames) * hold, W, H, len(frames), 0) + payload
assert len(splash) <= 24576
header(ROOT / "src/splash_data.h", "kSplash", splash, "uint8_t")
frames[0].save(ROOT.parent / "开机动画.gif", save_all=True, append_images=frames[1:],
               duration=hold, loop=0, disposal=2)
print(f"{len(frames)} frames, {len(splash)} bytes")
